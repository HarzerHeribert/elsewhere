"""Outline licensed Averia Serif Libre with a subtly irregular baseline. Requires fontTools."""
from pathlib import Path
from fontTools.ttLib import TTFont
from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from shutil import copyfile

root = Path(__file__).resolve().parents[1]
font_path = root / 'assets/brand/type/AveriaSerifLibre-Bold.ttf'
font = TTFont(font_path)
glyphs = font.getGlyphSet()
cmap = font.getBestCmap()
word = 'elsewhere'
advances = [font['hmtx'][cmap[ord(c)]][0] for c in word]
scale = 606 / (sum(advances) - 14 * (len(word) - 1))
rotations = [-2, 1.5, -1, 1.2, -1.5, .6, -1, 1.3, -2]
offsets = [1, -2, 2, -1, 2, -2, 1, 0, -1]
paths = []
x = 12
for char, advance, rotation, offset in zip(word, advances, rotations, offsets):
    pen = SVGPathPen(glyphs)
    # Font coordinates point up. Keep filled contours, including the open e counter.
    glyphs[cmap[ord(char)]].draw(TransformPen(pen, (scale, 0, 0, -scale, x, 96 + offset)))
    paths.append(f'<path transform="rotate({rotation} {x+advance*scale/2:.3f} 70)" d="{pen.getCommands()}"/>')
    x += (advance - 14) * scale
art = '<g fill="currentColor" stroke="none">' + ''.join(paths) + '</g>'
out = root / 'elsewhere/web/src/wordmarkArtwork.ts'
out.write_text('/** Generated by scripts/generate-wordmark.py. Averia Serif Libre, SIL OFL 1.1. */\nexport const wordmarkArtwork = ' + repr(art) + ';\n')
# Ship the original licensed font unchanged; its reserved names stay intact.
copyfile(font_path, root / 'elsewhere/web/public/brand/fonts/averia-serif-libre-bold.ttf')
print('Generated outlined wordmark and copied original local display font')
